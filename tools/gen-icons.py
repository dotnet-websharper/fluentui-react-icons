#!/usr/bin/env python3
"""Generate Library.fs for the @fluentui/react-icons binding.

The binding is a flat surface: every icon the npm package exports from
``lib/icons`` (the unsized ``Filled`` / ``Regular`` / ``Color`` icons) becomes
an ``[<Inline>]`` value that imports it, plus a helper in ``Icons.Helpers``
that turns it into a React element.

Usage (from the repository root, after ``npm install``)::

    python3 tools/gen-icons.py            # rewrite the binding
    python3 tools/gen-icons.py --check    # fail if the binding is out of date
"""

import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PKG = "@fluentui/react-icons"
MODULE = "WebSharper.React.FluentUI.Icons"
OUT = os.path.join(ROOT, MODULE, "Library.fs")

EXPORT_RE = re.compile(r"export declare const ([A-Za-z0-9_]+): FluentIcon")
CHUNK_RE = re.compile(r"chunk-(\d+)\.d\.ts$")


def package_dir() -> str:
    return os.path.join(ROOT, "node_modules", PKG)


def package_version() -> str:
    with open(os.path.join(package_dir(), "package.json"), encoding="utf-8") as f:
        return json.load(f)["version"]


def icon_names() -> list:
    """The icons in the package's own declaration order (chunk by chunk)."""
    icons_dir = os.path.join(package_dir(), "lib", "icons")
    chunks = glob.glob(os.path.join(icons_dir, "chunk-*.d.ts"))
    if not chunks:
        sys.exit(f"No chunk files under {icons_dir}; run `npm install` first.")
    chunks.sort(key=lambda p: int(CHUNK_RE.search(p).group(1)))
    names = []
    for chunk in chunks:
        with open(chunk, encoding="utf-8") as f:
            names += EXPORT_RE.findall(f.read())
    return names


def render(version: str, names: list) -> str:
    lines = [
        "// This file is generated by tools/gen-icons.py from the npm package",
        f"// {PKG} (version {version}). Do not edit it by hand; re-run the",
        "// generator (after `npm install`) to refresh the icon surface.",
        "namespace WebSharper.FluentUI.React",
        "    open WebSharper",
        "    open WebSharper.React",
        "    open WebSharper.JavaScript",
        "    [<JavaScript>]",
        "    module Icons =",
    ]
    for name in names:
        lines.append(
            f'        let [<Inline>] {name}<\'a> = '
            f'JS.Import<\'a>("{name}", "{PKG}")'
        )
    lines += ["", "        [<JavaScript>]", "        module Helpers ="]
    for name in names:
        helper = name[0].lower() + name[1:]
        lines.append(f"            let {helper} props = ReactHelpers.Elt {name} props []")
    return "\n".join(lines) + "\n"


def main() -> None:
    version = package_version()
    names = icon_names()
    content = render(version, names)
    check = "--check" in sys.argv
    if check:
        with open(OUT, encoding="utf-8", newline="") as f:
            if f.read() != content:
                sys.exit(f"{OUT} is out of date; run tools/gen-icons.py")
        print(f"{OUT} is up to date ({len(names)} icons, {PKG} {version}).")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    print(f"Wrote {OUT}: {len(names)} icons from {PKG} {version}.")


if __name__ == "__main__":
    main()